-- CT-027: in-app notifications for case followers. Rows hold ids only, never comment text or account details.
CREATE TABLE notifications
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    recipient_id BIGINT                      NOT NULL,
    case_id      BIGINT                      NOT NULL,
    type         VARCHAR(32)                 NOT NULL,
    comment_id   BIGINT,
    case_status  VARCHAR(32),
    event_id     VARCHAR(64)                 NOT NULL,
    read_at      TIMESTAMP WITHOUT TIME ZONE,
    created_at   TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CONSTRAINT pk_notifications PRIMARY KEY (id),
    CONSTRAINT fk_notifications_recipient FOREIGN KEY (recipient_id) REFERENCES users (id),
    CONSTRAINT fk_notifications_case FOREIGN KEY (case_id) REFERENCES cases (id),
    CONSTRAINT fk_notifications_comment FOREIGN KEY (comment_id) REFERENCES comments (id),
    CONSTRAINT ck_notifications_type CHECK (type IN ('NEW_COMMENT', 'CASE_STATUS_CHANGED')),
    CONSTRAINT ck_notifications_comment CHECK ((type = 'NEW_COMMENT') = (comment_id IS NOT NULL)),
    CONSTRAINT ck_notifications_case_status CHECK ((type = 'CASE_STATUS_CHANGED') = (case_status IS NOT NULL)),
    CONSTRAINT ck_notifications_case_status_value
        CHECK (case_status IS NULL OR case_status IN ('MISSING', 'FOUND_SAFE', 'FOUND_DECEASED', 'CLOSED')),
    -- One event reaches each recipient at most once.
    CONSTRAINT uq_notifications_event_recipient UNIQUE (event_id, recipient_id)
);

-- A recipient's list reads newest first; the unread count reads only unread rows.
CREATE INDEX idx_notifications_recipient_recent ON notifications (recipient_id, created_at DESC, id DESC);
CREATE INDEX idx_notifications_recipient_unread ON notifications (recipient_id) WHERE read_at IS NULL;

-- Fan-out reads a case's followers.
CREATE INDEX idx_case_follows_case ON case_follows (case_id);
