-- CT-025: one flat, pseudonymous discussion thread per public case.
-- A removed comment keeps its row so moderators can still see it (CT-019).
CREATE TABLE comments
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    case_id           BIGINT                      NOT NULL,
    author_id         BIGINT                      NOT NULL,
    body              VARCHAR(2000)               NOT NULL,
    moderation_status VARCHAR(32)                 NOT NULL DEFAULT 'VISIBLE',
    report_count      INTEGER                     NOT NULL DEFAULT 0,
    created_at        TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    removed_at        TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_comments PRIMARY KEY (id),
    CONSTRAINT fk_comments_case FOREIGN KEY (case_id) REFERENCES cases (id),
    CONSTRAINT fk_comments_author FOREIGN KEY (author_id) REFERENCES users (id),
    CONSTRAINT ck_comments_body_not_blank CHECK (btrim(body) <> ''),
    CONSTRAINT ck_comments_moderation_status CHECK (moderation_status IN ('VISIBLE', 'REMOVED')),
    CONSTRAINT ck_comments_report_count CHECK (report_count >= 0),
    CONSTRAINT ck_comments_removed_at CHECK ((moderation_status = 'REMOVED') = (removed_at IS NOT NULL))
);

-- The public thread reads visible comments newest first.
CREATE INDEX idx_comments_case_visible ON comments (case_id, created_at DESC, id DESC)
    WHERE moderation_status = 'VISIBLE';
CREATE INDEX idx_comments_author ON comments (author_id);

-- V14 left this FK out until comments existed.
ALTER TABLE content_reports
    ADD CONSTRAINT fk_content_reports_comment FOREIGN KEY (comment_id) REFERENCES comments (id);
